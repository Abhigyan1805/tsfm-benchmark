#!/usr/bin/env python3
"""Kaggle batch-kernel route for tsfm-benchmark (see docs/colab-handoff.md).

The D-drive machine orchestrates a GPU run on Kaggle: it packs the pending jobs
into a private GPU kernel, pushes it with the ``kaggle`` CLI, polls it to
completion, downloads the output, and ingests the result JSON back into the
repo's result cache.

The route is resumable and content-keyed: jobs whose ``<cache-key>.json`` is
already in the result directory are skipped, so re-running after a preemption
or a partial download only measures the gap. Only pending jobs are packed into
the kernel, and the kernel id is derived from the batch, so the same batch maps
to the same kernel.

Subcommands (all support ``--dry-run`` where they shell out):

* ``preflight`` -- verify the kaggle CLI is installed/authenticated and summarize
  how many jobs are pending vs cached.
* ``plan`` -- print the pending/cached split without touching the network.
* ``build`` -- write a kernel directory (``kernel.py`` + metadata) from a job file.
* ``push`` / ``status`` / ``poll`` / ``fetch`` -- the individual CLI steps.
* ``ingest`` -- copy result JSON from a fetched output directory into the cache.
* ``run`` -- build -> push -> poll -> fetch -> ingest, skipping cached jobs.

Examples:
    python scripts/kaggle_run.py plan --jobs jobs.json --out results/kaggle-01
    python scripts/kaggle_run.py run --jobs jobs.json --out results/kaggle-01 \\
        --ref "$(git rev-parse HEAD)" --pip 'timesfm[torch]' --pip chronos-forecasting
"""

