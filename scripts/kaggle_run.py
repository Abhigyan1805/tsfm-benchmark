def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Kaggle batch route for tsbench")
    subparsers = parser.add_subparsers(dest="cmd", required=True)

    preflight = subparsers.add_parser("preflight")
    preflight.add_argument("--jobs", required=True)
    preflight.add_argument("--out", required=True)
    preflight.add_argument("--dry-run", action="store_true")
    preflight.set_defaults(func=cmd_preflight)

    plan = subparsers.add_parser("plan")
    plan.add_argument("--jobs", required=True)
    plan.add_argument("--out", required=True)
    plan.add_argument("--ref", default="HEAD")
    plan.set_defaults(func=cmd_plan)

    for name, func in (("build", cmd_build), ("run", cmd_run)):
        sub = subparsers.add_parser(name)
        _add_batch_arguments(sub)
        sub.set_defaults(func=func)

    experiments_parser = subparsers.add_parser(
        "experiments", help="run experiment configs in a GPU kernel"
    )
    _add_experiment_arguments(experiments_parser)
    experiments_parser.set_defaults(func=cmd_experiments)

    push = subparsers.add_parser("push")
    push.add_argument("--workdir", required=True)
    push.add_argument("--dry-run", action="store_true")
    push.set_defaults(func=cmd_push)

    status = subparsers.add_parser("status")
    status.add_argument("kernel")
    status.add_argument("--dry-run", action="store_true")
    status.set_defaults(func=cmd_status)

    poll = subparsers.add_parser("poll")
    poll.add_argument("kernel")
    poll.add_argument("--timeout", type=float, default=3600.0)
    poll.add_argument("--interval", type=float, default=20.0)
    poll.add_argument("--dry-run", action="store_true")
    poll.set_defaults(func=cmd_poll)

    fetch = subparsers.add_parser("fetch")
    fetch.add_argument("kernel")
    fetch.add_argument("--dest", required=True)
    fetch.add_argument("--dry-run", action="store_true")
    fetch.set_defaults(func=cmd_fetch)

    ingest_parser = subparsers.add_parser("ingest")
    ingest_parser.add_argument("--dest", required=True)
    ingest_parser.add_argument("--out", required=True)
    ingest_parser.add_argument("--jobs", default=None)
    ingest_parser.set_defaults(func=cmd_ingest)

    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
