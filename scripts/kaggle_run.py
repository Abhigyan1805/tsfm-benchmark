COMPLETE_STATES = ("COMPLETE", "COMPLETED", "SUCCESS")
FAILED_STATES = ("ERROR", "FAILED", "CANCELLED")


def _load_colab_run() -> Any:
    """Load the sibling ``colab_run`` module without a package import."""
    spec = importlib.util.spec_from_file_location(
        "colab_run", SCRIPT_DIR / "colab_run.py"
    )
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {SCRIPT_DIR / 'colab_run.py'}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


colab_run = _load_colab_run()


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load_jobs(jobs_path: str | Path) -> list[dict[str, Any]]:
    """Read a job file (a list, or ``{"jobs": [...]}``)."""
    payload = json.loads(Path(jobs_path).read_text(encoding="utf-8"))
    if isinstance(payload, dict):
        payload = payload.get("jobs")
    if not isinstance(payload, list) or not payload:
        raise ValueError(f"{jobs_path} must contain a non-empty 'jobs' list")
    if not all(isinstance(job, dict) for job in payload):
        raise ValueError("every job must be a JSON object")
    return payload


def kernel_slug(jobs: list[dict[str, Any]], ref: str) -> str:
    """Deterministic, kaggle-valid slug for a (jobs batch, ref) pair."""
    digest = hashlib.sha256(
        colab_run.canonical_json({"ref": ref, "jobs": jobs}).encode("utf-8")
    ).hexdigest()[:12]
    return f"tsbench-gpu-{digest}"


def parse_username(config_text: str) -> str:
    """Extract the authenticated username from ``kaggle config view`` output."""
    match = re.search(r"^\s*[-*]?\s*username:\s*(\S+)\s*$", config_text, re.MULTILINE)
    if not match:
        raise ValueError("kaggle config view did not report a username")
    return match.group(1)


def partition_jobs(
    jobs: list[dict[str, Any]], out: Path
) -> tuple[list[tuple[int, dict[str, Any], str]], list[tuple[int, str]]]:
    """Split jobs into ``(pending, cached)`` using the content cache key."""
    pending: list[tuple[int, dict[str, Any], str]] = []
    cached: list[tuple[int, str]] = []
    for index, job in enumerate(jobs):
        series = colab_run.load_series(job)
        key = colab_run.cache_key(job, series)
        if (out / f"{key}.json").exists():
            cached.append((index, key))
        else:
            pending.append((index, job, key))
    return pending, cached


