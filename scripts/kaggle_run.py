#!/usr/bin/env python3
"""Kaggle batch-kernel route for tsfm-benchmark (see docs/colab-handoff.md).

The D-drive machine orchestrates a GPU run on Kaggle: it packs the pending jobs
into a private GPU kernel, pushes it with the ``kaggle`` CLI, polls it to
completion, downloads the output, and ingests the result JSON back into the
repo's result cache.

The route is resumable and content-keyed: jobs whose ``<cache-key>.json`` is
already in the result directory are skipped, so re-running after a preemption
or a partial download only measures the gap. Only pending jobs are packed into
the kernel, and the kernel id is derived from the batch, so the same batch maps
to the same kernel.

Subcommands (all support ``--dry-run`` where they shell out):

* ``preflight`` -- verify the kaggle CLI is installed/authenticated and summarize
  how many jobs are pending vs cached.
* ``plan`` -- print the pending/cached split without touching the network.
* ``build`` -- write a kernel directory (``kernel.py`` + metadata) from a job file.
* ``push`` / ``status`` / ``poll`` / ``fetch`` -- the individual CLI steps.
* ``ingest`` -- copy result JSON from a fetched output directory into the cache.
* ``run`` -- build -> push -> poll -> fetch -> ingest, skipping cached jobs.

Examples:
    python scripts/kaggle_run.py plan --jobs jobs.json --out results/kaggle-01
    python scripts/kaggle_run.py run --jobs jobs.json --out results/kaggle-01 \\
        --ref "$(git rev-parse HEAD)" --pip 'timesfm[torch]' --pip chronos-forecasting
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.util
import json
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_REPO = "https://github.com/Abhigyan1805/tsfm-benchmark.git"
COMPLETE_STATES = ("COMPLETE", "COMPLETED", "SUCCESS")
FAILED_STATES = ("ERROR", "FAILED", "CANCELLED")


def _load_colab_run() -> Any:
    """Load the sibling ``colab_run`` module without a package import."""
    spec = importlib.util.spec_from_file_location(
        "colab_run", SCRIPT_DIR / "colab_run.py"
    )
    if spec is None or spec.loader is None:
        raise ImportError(f"cannot load {SCRIPT_DIR / 'colab_run.py'}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


colab_run = _load_colab_run()


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def load_jobs(jobs_path: str | Path) -> list[dict[str, Any]]:
    """Read a job file (a list, or ``{"jobs": [...]}``)."""
    payload = json.loads(Path(jobs_path).read_text(encoding="utf-8"))
    if isinstance(payload, dict):
        payload = payload.get("jobs")
    if not isinstance(payload, list) or not payload:
        raise ValueError(f"{jobs_path} must contain a non-empty 'jobs' list")
    if not all(isinstance(job, dict) for job in payload):
        raise ValueError("every job must be a JSON object")
    return payload


def kernel_slug(jobs: list[dict[str, Any]], ref: str) -> str:
    """Deterministic, kaggle-valid slug for a (jobs batch, ref) pair."""
    digest = hashlib.sha256(
        colab_run.canonical_json({"ref": ref, "jobs": jobs}).encode("utf-8")
    ).hexdigest()[:12]
    return f"tsbench-gpu-{digest}"


def parse_username(config_text: str) -> str:
    """Extract the authenticated username from ``kaggle config view`` output."""
    match = re.search(r"^\s*[-*]?\s*username:\s*(\S+)\s*$", config_text, re.MULTILINE)
    if not match:
        raise ValueError("kaggle config view did not report a username")
    return match.group(1)


def partition_jobs(
    jobs: list[dict[str, Any]], out: Path
) -> tuple[list[tuple[int, dict[str, Any], str]], list[tuple[int, str]]]:
    """Split jobs into ``(pending, cached)`` using the content cache key."""
    pending: list[tuple[int, dict[str, Any], str]] = []
    cached: list[tuple[int, str]] = []
    for index, job in enumerate(jobs):
        series = colab_run.load_series(job)
        key = colab_run.cache_key(job, series)
        if (out / f"{key}.json").exists():
            cached.append((index, key))
        else:
            pending.append((index, job, key))
    return pending, cached


def kernel_source(
    jobs: list[dict[str, Any]],
    *,
    repo: str,
    ref: str,
    run_name: str,
    pip_packages: list[str],
) -> str:
    """Render the self-contained kernel script that runs the batch on Kaggle."""
    jobs_b64 = base64.b64encode(
        colab_run.canonical_json({"jobs": jobs}).encode("utf-8")
    ).decode("ascii")
    return f'''"""Generated by scripts/kaggle_run.py; do not edit by hand."""

import base64
import json
import os
import subprocess
import sys
from pathlib import Path

JOBS = json.loads(base64.b64decode("{jobs_b64}").decode("utf-8"))["jobs"]
REPO = {repo!r}
REF = {ref!r}
PIP_PACKAGES = {pip_packages!r}
RUN_NAME = {run_name!r}

REPO_DIR = Path("/tmp/tsbench-repo")
RUN_DIR = Path("/kaggle/working") / RUN_NAME
JOBS_FILE = Path("/tmp/tsbench-jobs.json")

os.environ.setdefault("TSBENCH_ALLOW_MODEL_DOWNLOAD", "1")

if PIP_PACKAGES:
    subprocess.run(
        [sys.executable, "-m", "pip", "install", "-q", *PIP_PACKAGES], check=True
    )

subprocess.run(["git", "clone", "--quiet", REPO, str(REPO_DIR)], check=True)
subprocess.run(
    ["git", "-C", str(REPO_DIR), "checkout", "--quiet", REF], check=True
)

JOBS_FILE.write_text(json.dumps({{"jobs": JOBS}}), encoding="utf-8")
runner = REPO_DIR / "scripts" / "colab_run.py"
subprocess.run(
    [sys.executable, str(runner), "run", "--jobs", str(JOBS_FILE), "--out",
     str(RUN_DIR)],
    check=True,
)
subprocess.run(
    [sys.executable, str(runner), "bundle", "--out", str(RUN_DIR)], check=True
)
print("KAGGLE_RUN_DIR", RUN_DIR)
'''


def build_kernel_dir(
    workdir: Path,
    jobs: list[dict[str, Any]],
    *,
    owner: str,
    slug: str,
    title: str,
    repo: str,
    ref: str,
    run_name: str,
    pip_packages: list[str],
    dataset_sources: list[str] | None = None,
    enable_gpu: bool = True,
    enable_internet: bool = True,
) -> dict[str, Any]:
    """Write ``kernel.py`` and ``kernel-metadata.json``; return the metadata."""
    workdir.mkdir(parents=True, exist_ok=True)
    source = kernel_source(
        jobs,
        repo=repo,
        ref=ref,
        run_name=run_name,
        pip_packages=pip_packages,
    )
    (workdir / "kernel.py").write_text(source, encoding="utf-8")
    metadata = {
        "id": f"{owner}/{slug}",
        "title": title,
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true" if enable_gpu else "false",
        "enable_internet": "true" if enable_internet else "false",
        "dataset_sources": list(dataset_sources or []),
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (workdir / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return metadata


def result_files(root: Path) -> list[Path]:
    """All result JSON files under ``root`` (tar archives extracted first)."""
    files: list[Path] = []
    for path in sorted(root.rglob("*.json")):
        if path.name in {"manifest.json", "jobs.json", "kernel-metadata.json"}:
            continue
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if isinstance(payload, dict) and "cache_key" in payload:
            files.append(path)
    return files


def _extract_archives(root: Path, destination: Path) -> list[Path]:
    """Extract every ``*.tar.gz`` under ``root`` into ``destination``."""
    extracted: list[Path] = []
    for archive in sorted(root.rglob("*.tar.gz")):
        with tarfile.open(archive, "r:gz") as handle:
            members = [
                member
                for member in handle.getmembers()
                if member.isfile() and not member.name.endswith(".tmp")
            ]
            try:
                handle.extractall(destination, members=members, filter="data")
            except TypeError:  # Python < 3.12 has no extraction filters
                handle.extractall(destination, members=members)
        extracted.append(archive)
    return extracted


def ingest(
    fetched_dir: Path, out: Path, expected_keys: list[str] | None = None
) -> dict[str, Any]:
    """Merge fetched result JSON into the cache; report ingested/missing."""
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        scratch = Path(tmp)
        extracted = _extract_archives(fetched_dir, scratch)
        search_root = scratch if extracted else fetched_dir
        ingested: list[str] = []
        skipped: list[str] = []
        for path in result_files(search_root):
            payload = json.loads(path.read_text(encoding="utf-8"))
            key = str(payload["cache_key"])
            target = out / f"{key}.json"
            if target.exists():
                skipped.append(key)
                continue
            colab_run.write_json_atomic(target, payload)
            ingested.append(key)
    expected = [str(key) for key in (expected_keys or [])]
    missing = [key for key in expected if not (out / f"{key}.json").exists()]
    summary = {
        "ingested": sorted(ingested),
        "skipped": sorted(skipped),
        "missing": sorted(missing),
        "fetched_dir": str(fetched_dir),
        "out": str(out),
    }
    manifest_path = out / "ingest-manifest.json"
    colab_run.write_json_atomic(manifest_path, {"updated_at": _utc_now(), **summary})
    return summary


def run_command(cmd: list[str], dry_run: bool = False) -> int:
    """Print and (unless ``--dry-run``) execute a CLI command."""
    print("$ " + " ".join(cmd), flush=True)
    if dry_run:
        return 0
    completed = subprocess.run(cmd, text=True)
    return completed.returncode


def kaggle_username(dry_run: bool = False) -> str:
    """Return the authenticated kaggle username."""
    if dry_run:
        return "dry-run-owner"
    if shutil.which("kaggle") is None:
        raise RuntimeError("kaggle CLI not found on PATH; pip install kaggle")
    completed = subprocess.run(
        ["kaggle", "config", "view"], capture_output=True, text=True
    )
    if completed.returncode != 0:
        raise RuntimeError(
            "kaggle config view failed; run 'kaggle config set' or place "
            "~/.kaggle/kaggle.json"
        )
    return parse_username(completed.stdout)


def poll_until_done(
    kernel_id: str,
    timeout: float,
    interval: float,
    dry_run: bool = False,
) -> str:
    """Poll ``kaggle kernels status`` until a terminal state or timeout."""
    deadline = time.monotonic() + timeout
    while True:
        if dry_run:
            print(f"[dry-run] kaggle kernels status {kernel_id} -> COMPLETE")
            return "COMPLETE"
        completed = subprocess.run(
            ["kaggle", "kernels", "status", kernel_id],
            capture_output=True,
            text=True,
        )
        status = completed.stdout.strip()
        print(f"[kaggle] {kernel_id}: {status}", flush=True)
        upper = status.upper()
        if any(state in upper for state in COMPLETE_STATES):
            return status
        if any(state in upper for state in FAILED_STATES):
            raise RuntimeError(f"kernel {kernel_id} ended: {status}")
        if time.monotonic() >= deadline:
            raise TimeoutError(f"kernel {kernel_id} still running: {status}")
        time.sleep(interval)


def cmd_preflight(args: argparse.Namespace) -> int:
    jobs = load_jobs(args.jobs)
    out = Path(args.out)
    pending, cached = partition_jobs(jobs, out)
    print(f"kaggle CLI: {shutil.which('kaggle') or 'MISSING'}")
    print(f"jobs: {len(jobs)} total, {len(pending)} pending, {len(cached)} cached")
    if shutil.which("kaggle") is not None and not args.dry_run:
        print(f"username: {kaggle_username()}")
    return 0 if pending or cached else 1


def cmd_plan(args: argparse.Namespace) -> int:
    jobs = load_jobs(args.jobs)
    out = Path(args.out)
    pending, cached = partition_jobs(jobs, out)
    plan = {
        "jobs_file": str(args.jobs),
        "out": str(out),
        "total": len(jobs),
        "pending": [{"job_index": index, "cache_key": key} for index, _, key in pending],
        "cached": [{"job_index": index, "cache_key": key} for index, key in cached],
        "ref": args.ref,
    }
    print(json.dumps(plan, indent=2, sort_keys=True))
    return 0


def _resolve_build(args: argparse.Namespace) -> dict[str, Any]:
    jobs = load_jobs(args.jobs)
    out = Path(args.out)
    pending, cached = partition_jobs(jobs, out)
    pending_jobs = [job for _, job, _ in pending]
    if not pending_jobs:
        return {"pending_jobs": [], "cached": cached, "jobs": jobs}
    ref = args.ref
    slug = args.slug or kernel_slug(pending_jobs, ref)
    owner = args.owner or kaggle_username(dry_run=args.dry_run)
    run_name = args.run_name or f"run-{slug}"
    workdir = Path(args.workdir) if args.workdir else Path("results/kaggle") / slug
    metadata = build_kernel_dir(
        workdir,
        pending_jobs,
        owner=owner,
        slug=slug,
        title=args.title or f"tsbench GPU batch {slug}",
        repo=args.repo,
        ref=ref,
        run_name=run_name,
        pip_packages=args.pip,
        dataset_sources=args.dataset_source,
        enable_gpu=not args.cpu,
        enable_internet=not args.no_internet,
    )
    return {
        "pending_jobs": pending_jobs,
        "cached": cached,
        "metadata": metadata,
        "workdir": workdir,
        "run_name": run_name,
        "keys": [key for _, _, key in pending],
    }


def cmd_build(args: argparse.Namespace) -> int:
    resolved = _resolve_build(args)
    if not resolved["pending_jobs"]:
        print("build: no pending jobs, nothing to pack")
        return 0
    print(f"build: {resolved['metadata']['id']} -> {resolved['workdir']}")
    print(f"build: {len(resolved['pending_jobs'])} pending jobs")
    return 0


def cmd_push(args: argparse.Namespace) -> int:
    workdir = Path(args.workdir)
    if not (workdir / "kernel-metadata.json").exists():
        print(f"push: {workdir} has no kernel-metadata.json", file=sys.stderr)
        return 2
    return run_command(
        ["kaggle", "kernels", "push", "-p", str(workdir)], dry_run=args.dry_run
    )


def cmd_status(args: argparse.Namespace) -> int:
    return run_command(
        ["kaggle", "kernels", "status", args.kernel], dry_run=args.dry_run
    )


def cmd_poll(args: argparse.Namespace) -> int:
    status = poll_until_done(args.kernel, args.timeout, args.interval, args.dry_run)
    print(f"poll: {args.kernel} -> {status}")
    return 0


def cmd_fetch(args: argparse.Namespace) -> int:
    dest = Path(args.dest)
    dest.mkdir(parents=True, exist_ok=True)
    return run_command(
        ["kaggle", "kernels", "output", args.kernel, "-p", str(dest)],
        dry_run=args.dry_run,
    )


def cmd_ingest(args: argparse.Namespace) -> int:
    expected = None
    if args.jobs:
        jobs = load_jobs(args.jobs)
        pending, _ = partition_jobs(jobs, Path(args.out))
        expected = [key for _, _, key in pending]
    summary = ingest(Path(args.dest), Path(args.out), expected)
    print(
        f"ingest: +{len(summary['ingested'])} "
        f"skipped={len(summary['skipped'])} missing={len(summary['missing'])}"
    )
    return 1 if summary["missing"] else 0


def cmd_run(args: argparse.Namespace) -> int:
    resolved = _resolve_build(args)
    if not resolved["pending_jobs"]:
        print(
            f"run: all {len(resolved['cached'])} jobs already cached in {args.out}"
        )
        return 0
    workdir = resolved["workdir"]
    kernel_id = resolved["metadata"]["id"]
    keys = resolved["keys"]
    print(
        f"run: {len(resolved['pending_jobs'])} pending jobs, "
        f"{len(resolved['cached'])} cached -> {kernel_id}"
    )
    push_code = run_command(
        ["kaggle", "kernels", "push", "-p", str(workdir)], dry_run=args.dry_run
    )
    if push_code != 0:
        return push_code
    try:
        status = poll_until_done(kernel_id, args.timeout, args.interval, args.dry_run)
    except TimeoutError as exc:
        print(f"run: {exc}", file=sys.stderr)
        return 1
    except RuntimeError as exc:
        print(f"run: {exc}", file=sys.stderr)
        status = "ERROR"
    kernel_failed = any(state in status.upper() for state in FAILED_STATES)
    dest = Path(args.fetch_dest) if args.fetch_dest else workdir / "output"
    dest.mkdir(parents=True, exist_ok=True)
    fetch_code = run_command(
        ["kaggle", "kernels", "output", kernel_id, "-p", str(dest)],
        dry_run=args.dry_run,
    )
    if fetch_code != 0:
        return fetch_code
    if args.dry_run:
        print("run: dry-run complete; skipped ingest")
        return 1 if kernel_failed else 0
    summary = ingest(dest, Path(args.out), keys)
    print(
        f"run: ingested={len(summary['ingested'])} "
        f"skipped={len(summary['skipped'])} missing={len(summary['missing'])}"
    )
    return 1 if (kernel_failed or summary["missing"]) else 0


def _add_batch_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--jobs", required=True, help="JSON job file")
    parser.add_argument("--out", required=True, help="result cache directory")
    parser.add_argument("--ref", required=True, help="repo git ref/sha in the kernel")
    parser.add_argument("--repo", default=DEFAULT_REPO)
    parser.add_argument("--workdir", default=None, help="kernel build directory")
    parser.add_argument("--owner", default=None, help="kaggle owner override")
    parser.add_argument("--slug", default=None, help="kernel slug override")
    parser.add_argument("--title", default=None)
    parser.add_argument("--run-name", default=None, help="kernel working subdir")
    parser.add_argument(
        "--pip", action="append", default=[], help="pip package (repeatable)"
    )
    parser.add_argument(
        "--dataset-source",
        action="append",
        default=[],
        help="kaggle dataset source for series_path jobs (repeatable)",
    )
    parser.add_argument("--fetch-dest", default=None)
    parser.add_argument("--timeout", type=float, default=3600.0)
    parser.add_argument("--interval", type=float, default=20.0)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--cpu", action="store_true", help="disable GPU in metadata")
    parser.add_argument("--no-internet", action="store_true")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Kaggle batch route for tsbench")
    subparsers = parser.add_subparsers(dest="cmd", required=True)

    preflight = subparsers.add_parser("preflight")
    preflight.add_argument("--jobs", required=True)
    preflight.add_argument("--out", required=True)
    preflight.add_argument("--dry-run", action="store_true")
    preflight.set_defaults(func=cmd_preflight)

    plan = subparsers.add_parser("plan")
    plan.add_argument("--jobs", required=True)
    plan.add_argument("--out", required=True)
    plan.add_argument("--ref", default="HEAD")
    plan.set_defaults(func=cmd_plan)

    for name, func in (("build", cmd_build), ("run", cmd_run)):
        sub = subparsers.add_parser(name)
        _add_batch_arguments(sub)
        sub.set_defaults(func=func)

    push = subparsers.add_parser("push")
    push.add_argument("--workdir", required=True)
    push.add_argument("--dry-run", action="store_true")
    push.set_defaults(func=cmd_push)

    status = subparsers.add_parser("status")
    status.add_argument("kernel")
    status.add_argument("--dry-run", action="store_true")
    status.set_defaults(func=cmd_status)

    poll = subparsers.add_parser("poll")
    poll.add_argument("kernel")
    poll.add_argument("--timeout", type=float, default=3600.0)
    poll.add_argument("--interval", type=float, default=20.0)
    poll.add_argument("--dry-run", action="store_true")
    poll.set_defaults(func=cmd_poll)

    fetch = subparsers.add_parser("fetch")
    fetch.add_argument("kernel")
    fetch.add_argument("--dest", required=True)
    fetch.add_argument("--dry-run", action="store_true")
    fetch.set_defaults(func=cmd_fetch)

    ingest_parser = subparsers.add_parser("ingest")
    ingest_parser.add_argument("--dest", required=True)
    ingest_parser.add_argument("--out", required=True)
    ingest_parser.add_argument("--jobs", default=None)
    ingest_parser.set_defaults(func=cmd_ingest)

    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
