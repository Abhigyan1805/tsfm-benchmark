def build_kernel_dir(
    workdir: Path,
    jobs: list[dict[str, Any]],
    *,
    owner: str,
    slug: str,
    title: str,
    repo: str,
    ref: str,
    run_name: str,
    pip_packages: list[str],
    dataset_sources: list[str] | None = None,
    enable_gpu: bool = True,
    enable_internet: bool = True,
    source: str | None = None,
) -> dict[str, Any]:
    """Write ``kernel.py`` and ``kernel-metadata.json``; return the metadata.

    ``source`` overrides the generated batch source (used by the experiment
    route); when omitted the job-batch source is generated from ``jobs``.
    """
    workdir.mkdir(parents=True, exist_ok=True)
    if source is None:
        source = kernel_source(
            jobs,
            repo=repo,
            ref=ref,
            run_name=run_name,
            pip_packages=pip_packages,
        )
    (workdir / "kernel.py").write_text(source, encoding="utf-8")
    metadata = {
        "id": f"{owner}/{slug}",
        "title": title,
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true" if enable_gpu else "false",
        "enable_internet": "true" if enable_internet else "false",
        "dataset_sources": list(dataset_sources or []),
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    (workdir / "kernel-metadata.json").write_text(
        json.dumps(metadata, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return metadata


def experiment_slug(configs: list[str], ref: str) -> str:
    """Deterministic, kaggle-valid slug for an (experiment batch, ref) pair."""
    digest = hashlib.sha256(
        colab_run.canonical_json(
            {"kind": "experiments", "ref": ref, "configs": list(configs)}
        ).encode("utf-8")
    ).hexdigest()[:12]
    return f"tsbench-gpu-exp-{digest}"


